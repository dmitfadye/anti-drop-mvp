def check_quiz(answers: list[int]) -> dict:
    """answers — индексы выбранных вариантов. Возвращает результат + кешбэк."""
    details = []
    score = 0
    for i, item in enumerate(QUIZ):
        picked = answers[i] if i < len(answers) else -1
        ok = picked == item["correct"]
        score += int(ok)
        details.append({"q": item["q"], "ok": ok, "explain": item["explain"]})
    passed = score >= PASS_THRESHOLD
    return {
        "score": score,
        "total": len(QUIZ),
        "passed": passed,
        "cashback": CASHBACK_REWARD if passed else 0,
        "message": f"🎉 Кешбэк {CASHBACK_REWARD} ₽ начислен! Вы защищены." if passed else f"Набрано {score}/{len(QUIZ)}. Пройдите ещё раз и получите {CASHBACK_REWARD} ₽.",
        "details": details,
    }
