def check_quiz(answers: list[int]) -> dict:
    """answers — индексы выбранных вариантов. Учебный результат, T18: выплата НЕ производится."""
    details = []
    score = 0
    for i, item in enumerate(QUIZ):
        picked = answers[i] if i < len(answers) else -1
        ok = picked == item["correct"]
        score += int(ok)
        details.append({"q": item["q"], "ok": ok, "explain": item["explain"]})
    passed = score >= PASS_THRESHOLD
    return {
        "score": score,
        "total": len(QUIZ),
        "passed": passed,
        "cashback": CASHBACK_REWARD if passed else 0,
        "reward_status": "simulated",  # T18: условная награда, реального начисления нет
        "message": (
            f"🎉 Зачёт! Учебный кешбэк {CASHBACK_REWARD} ₽ (демо: деньги не начисляются)."
            if passed
            else f"Набрано {score}/{len(QUIZ)}. Пройдите ещё раз — учебный приз {CASHBACK_REWARD} ₽."
        ),
        "details": details,
    }
